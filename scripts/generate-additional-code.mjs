import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";
import { format } from "prettier";
import { vanilla } from "../examples/additional-vanilla.mjs";

const source = await readFile(new URL("../app/ui/ModernDemos.tsx", import.meta.url), "utf8");
const css = await format(await readFile(new URL("../app/ui/modern-demos.css", import.meta.url), "utf8"), { parser: "css", printWidth: 90 });
const file = ts.createSourceFile("ModernDemos.tsx", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const names = { "date-range-picker": "DateRangeDemo", "time-field": "TimeFieldDemo", "multi-select": "MultiSelectDemo", rating: "RatingDemo", menubar: "MenubarDemo", questionnaire: "QuestionnaireDemo", "chat-message": "ChatMessageDemo", "message-scroller": "MessageScrollerDemo", attachment: "AttachmentDemo" };
const samples = {};
for (const [slug, name] of Object.entries(names)) {
  const declaration = file.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === name);
  if (!declaration) throw new Error(`Missing demo: ${name}`);
  const jsx = ts.transpileModule(declaration.getText(file).replace("export function", "export default function"), { fileName: "Component.tsx", compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, jsx: ts.JsxEmit.Preserve } }).outputText;
  samples[slug] = {
    vanilla: [{ name: "index.html", language: "html", code: '<!doctype html>\n<html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><link rel="stylesheet" href="styles.css"></head><body>\n' + vanilla[slug].html + '\n<script src="script.js" defer></script></body></html>' }, { name: "styles.css", language: "css", code: css }, { name: "script.js", language: "js", code: vanilla[slug].js }],
    react: [{ name: "Component.jsx", language: "jsx", code: 'import { useEffect, useId, useRef, useState } from "react";\nimport "./styles.css";\n\n' + jsx }, { name: "styles.css", language: "css", code: css }],
  };
  for (const family of ['vanilla', 'react']) {
    for (const sample of samples[slug][family]) {
      sample.code = await format(sample.code, { parser: sample.language === 'html' ? 'html' : sample.language === 'css' ? 'css' : 'babel', printWidth: 90 });
    }
  }
}
// Share CSS once in the generated module so each catalog entry stays inexpensive.
const literal = value => '`' + value.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${') + '`';
const lines = ['// Generated by scripts/generate-additional-code.mjs from the actual React demos.', 'import type { CodeBundle } from "./catalog";', `const styles = ${literal(css)};`, 'export const additionalCode: Record<string, CodeBundle> = {'];
for (const [slug, bundle] of Object.entries(samples)) {
  lines.push(`  ${JSON.stringify(slug)}: {`);
  for (const family of ['vanilla', 'react']) {
    lines.push(`    ${family}: [`);
    for (const sample of bundle[family]) lines.push(`      { name: ${JSON.stringify(sample.name)}, language: ${JSON.stringify(sample.language)}, code: ${sample.language === 'css' ? 'styles' : literal(sample.code)} },`);
    lines.push('    ],');
  }
  lines.push('  },');
}
lines.push('};', '');
await writeFile(new URL('../lib/additional-code.ts', import.meta.url), lines.join('\n'));
